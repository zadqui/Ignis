"""Identifier-only alternatives of versioned review files that contain source text.

Writes NEW files next to the originals (originals untouched): every source-text column is replaced by a sha256 of
the text plus the locator (doc_id, page, sentence index), and the document's publication class is added, so the
text can be re-hydrated locally from data/corpus/doc_sentences.parquet and checked against the hash.
"""

from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path
from typing import Any

import duckdb
import yaml

from ..publication import Policy

ANNOTATION = Path("reviews/reference_set/annotation_sheet.csv")
SEED_QUEUE = Path("reviews/queue/m5_seed_queue.yaml")
TEXT_COLS = ("context_before", "sentence", "context_after", "claim", "claim_quote")


def _sha(x: str | None) -> str:
    return hashlib.sha256((x or "").encode("utf-8")).hexdigest()[:16] if x else ""


def _classes(documents: Path, policy: Policy) -> dict[str, dict[str, Any]]:
    rows = duckdb.connect().execute("SELECT * FROM read_parquet(?)", [str(documents)]).fetchdf().to_dict("records")
    return {r["doc_id"]: policy.classify(r).as_row() for r in rows}


def redact_annotation_sheet(src: Path, out: Path, cls: dict[str, dict[str, Any]]) -> int:
    with src.open(encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        return 0
    keep = [c for c in rows[0] if c not in TEXT_COLS]
    cols = keep + [f"{c}_sha256" for c in TEXT_COLS if c in rows[0]] + ["pub_class", "license_label"]
    with out.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for r in rows:
            c = cls.get(r["doc_id"], {})
            w.writerow({**{k: r[k] for k in keep}, **{f"{k}_sha256": _sha(r.get(k)) for k in TEXT_COLS if k in r},
                        "pub_class": c.get("pub_class", "withheld"), "license_label": c.get("license_label", "")})
    return len(rows)


def redact_seed_queue(src: Path, out: Path, cls: dict[str, dict[str, Any]]) -> int:
    d = yaml.safe_load(src.read_text(encoding="utf-8"))
    items = []
    for q in d.get("queue", []):
        c = cls.get(q.get("doc_id"), {})
        items.append({**{k: v for k, v in q.items() if k not in ("claim", "quote")},
                      "claim_sha256": _sha(q.get("claim")), "quote_sha256": _sha(q.get("quote")),
                      "pub_class": c.get("pub_class", "withheld"), "license_label": c.get("license_label", "")})
    header = ("# Identifier-only copy of m5_seed_queue.yaml (claims and quotes replaced by sha256; re-hydrate locally\n"
              "# from data/findings by finding_id). NOT a review. Generated by `fif-app redact-versioned`.\n")
    out.write_text(header + yaml.safe_dump({"queue": items}, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return len(items)


def run(documents: Path = Path("data/corpus/documents.parquet")) -> dict[str, Any]:
    cls = _classes(documents, Policy())
    res = {}
    if ANNOTATION.exists():
        out = ANNOTATION.with_name(ANNOTATION.stem + ".ids.csv")
        res[str(out)] = redact_annotation_sheet(ANNOTATION, out, cls)
    if SEED_QUEUE.exists():
        out = SEED_QUEUE.with_name(SEED_QUEUE.stem + ".ids.yaml")
        res[str(out)] = redact_seed_queue(SEED_QUEUE, out, cls)
    print(json.dumps(res))
    return res
